import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { Link } from 'react-router-dom'
import * as api from '@/features/platform/support/api'
import { removeSupportData, supportKeys } from '@/features/platform/support/hooks'
import { makeArtifact, makeRestore, makeSession } from '@/features/platform/support/test-fixtures'
import type { SupportSession } from '@/features/platform/support/types'
import { paged, renderPlatform } from '@/features/platform/test-utils'
import { ApiError } from '@/lib/api/client'
import { PlatformSupportSessionPage } from './platform-support-session-page'

vi.mock('@/features/platform/support/api')
beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(api.getSession).mockResolvedValue(makeSession())
  vi.mocked(api.getSupportJobs).mockResolvedValue([])
  vi.mocked(api.getSupportArtifacts).mockResolvedValue(paged([makeArtifact()]))
  vi.mocked(api.getSupportArtifact).mockResolvedValue(makeArtifact())
  vi.mocked(api.getSupportRuns).mockResolvedValue(paged([]))
  vi.mocked(api.getSupportDownloads).mockResolvedValue(paged([]))
  vi.mocked(api.getSupportRestores).mockResolvedValue(paged([]))
  vi.mocked(api.getSessionAudit).mockResolvedValue(paged([]))
  vi.mocked(api.getSupportDownloadAvailability).mockResolvedValue({ available: true, reason: null, checksum: 'sha', sizeBytes: 4096, replicas: [] })
})
function mount(search = '') {
  return renderPlatform(<PlatformSupportSessionPage />, { path: `/platform/support-sessions/support-a${search}`, route: '/platform/support-sessions/:sessionId' })
}
const dataFunctions = () => [api.getSupportJobs, api.getSupportRuns, api.getSupportArtifacts, api.getSupportArtifact, api.getSupportDownloads, api.getSupportDownloadAvailability, api.getSupportDownloadStatus, api.getSupportRestores, api.getSupportRestore, api.getSupportRestoreTargets]
describe('support session detail', () => {
  it('metadata-only permits viewing, but disables Download and Restore actions and makes no privileged requests', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ permissions: ['ViewBackupMetadata'] }))
    mount('?tab=browser&artifact=artifact-a')
    await screen.findByRole('heading', { name: /Acme A.Ş. · (?:Support Session|Destek Oturumu)/ })
    await screen.findByRole('button', { name: "Geri Yükle…" })
    expect(screen.getByRole('tab', { name: "Yedekleme Gezgini" })).toBeEnabled()
    expect(screen.getByRole('tab', { name: "İndirmeler" })).toBeEnabled()
    expect(screen.getByRole('tab', { name: "Geri Yükleme İşlemleri" })).toBeEnabled()
    expect(screen.getByRole('button', { name: "İndir" })).toBeDisabled()
    expect(screen.getByRole('button', { name: "Geri Yükle…" })).toBeDisabled()
    expect(api.getSupportDownloadAvailability).not.toHaveBeenCalled()
    expect(api.getSupportRestoreTargets).not.toHaveBeenCalled()
    expect(await screen.findByText("Kaynak sağlama toplamı")).toBeInTheDocument()
    expect(screen.queryByText('Depolama hedefi')).not.toBeInTheDocument()
  })
  it('DownloadBackup enables download but not restore; RestoreBackup enables restore but not download', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ permissions: ['ViewBackupMetadata', 'DownloadBackup'] }))
    const view = mount('?tab=browser&artifact=artifact-a')
    await waitFor(() => expect(screen.getByRole('button', { name: "İndir" })).toBeEnabled())
    expect(screen.getByRole('button', { name: "Geri Yükle…" })).toBeDisabled()
    view.unmount()
    vi.mocked(api.getSupportDownloadAvailability).mockClear()
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ permissions: ['ViewBackupMetadata', 'RestoreBackup'] }))
    mount('?tab=browser&artifact=artifact-a')
    await waitFor(() => expect(screen.getByRole('button', { name: "Geri Yükle…" })).toBeEnabled())
    expect(screen.getByRole('button', { name: "İndir" })).toBeDisabled()
    expect(api.getSupportDownloadAvailability).not.toHaveBeenCalled()
  })
  it.each(['Expired', 'Closed', 'Revoked'] as const)('%s sessions disable all data tabs and Close and never query customer resources', async status => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ status }))
    mount('?tab=browser&artifact=artifact-a&restoreArtifact=artifact-a&restoreId=restore-a')
    await screen.findByRole('heading', { name: /Acme A.Ş. · (?:Support Session|Destek Oturumu)/ })
    expect(screen.getByRole('button', { name: "Oturumu kapat" })).toBeDisabled()
    for (const name of ['Backup Browser', 'Downloads', 'Restore Operations', 'Yedekleme Gezgini', 'İndirmeler', 'Geri Yükleme İşlemleri']) {
      const tab = screen.queryByRole('tab', { name })
      if (tab) expect(tab).toBeDisabled()
    }
    expect(screen.getByText(/Müşteri verilerine erişim ve tüm işlemler kapalıdır/)).toBeInTheDocument()
    for (const fn of dataFunctions()) expect(fn).not.toHaveBeenCalled()
    expect(api.closeSession).not.toHaveBeenCalled()
  })
  it('non-owners can only review/audit/revoke, never load metadata or close', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ isOwner: false }))
    mount('?tab=downloads')
    expect(await screen.findByRole('button', { name: "Erişimi geri al" })).toBeEnabled()
    expect(screen.queryByRole('button', { name: "Oturumu kapat" })).not.toBeInTheDocument()
    for (const fn of dataFunctions()) expect(fn).not.toHaveBeenCalled()
    expect(screen.getByText(/Bu oturumun sahibi değilsiniz/)).toBeInTheDocument()
  })
  it('requires confirmation before close, POSTs once, and removes all customer caches while retaining view and audit', async () => {
    const session = makeSession()
    vi.mocked(api.closeSession).mockResolvedValue({ ...session, status: 'Closed' })
    const { client } = mount()
    await screen.findByRole('button', { name: "Oturumu kapat" })
    const scope = { sessionId: session.id, tenantId: session.tenantId, enabled: true }
    for (const resource of ['jobs', 'runs', 'artifacts', 'downloads', 'restores']) client.setQueryData(supportKeys.data(scope, resource, 'secret'), { customer: resource })
    client.setQueryData(supportKeys.data(scope, 'audit'), paged([]))
    fireEvent.click(screen.getByRole('button', { name: "Oturumu kapat" }))
    expect(api.closeSession).not.toHaveBeenCalled()
    fireEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Oturumu kapat' }))
    await waitFor(() => expect(screen.getByRole('button', { name: "Oturumu kapat" })).toBeDisabled())
    expect(api.closeSession).toHaveBeenCalledOnce()
    expect(api.closeSession).toHaveBeenCalledWith('support-a')
    for (const resource of ['jobs', 'runs', 'artifacts', 'downloads', 'restores']) expect(client.getQueryData(supportKeys.data(scope, resource, 'secret'))).toBeUndefined()
    expect(client.getQueryData(supportKeys.data(scope, 'audit'))).toEqual(paged([]))
    expect(client.getQueryData<SupportSession>(supportKeys.session(session.id))?.status).toBe('Closed')
  })
  it('revoke requires a non-whitespace reason and clears customer cache on success', async () => {
    const session = makeSession({ isOwner: false })
    vi.mocked(api.getSession).mockResolvedValue(session)
    vi.mocked(api.revokeSession).mockResolvedValue({ ...session, status: 'Revoked' })
    const { client } = mount()
    fireEvent.click(await screen.findByRole('button', { name: "Erişimi geri al" }))
    const dialog = await screen.findByRole('dialog')
    fireEvent.change(within(dialog).getByLabelText('Gerekçe'), { target: { value: '   ' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Erişimi geri al' }))
    expect(api.revokeSession).not.toHaveBeenCalled()
    expect(within(dialog).getByRole('alert')).toHaveTextContent('Gerekçe zorunludur')
    const scope = { sessionId: session.id, tenantId: session.tenantId, enabled: true }
    client.setQueryData(supportKeys.data(scope, 'artifacts'), ['customer-secret'])
    fireEvent.change(within(dialog).getByLabelText('Gerekçe'), { target: { value: '  Müşteri talebi  ' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Erişimi geri al' }))
    await waitFor(() => expect(api.revokeSession).toHaveBeenCalledWith('support-a', 'Müşteri talebi'))
    await waitFor(() => expect(client.getQueryData(supportKeys.data(scope, 'artifacts'))).toBeUndefined())
  })
  it('403 support_access_denied renders the authorization state with reason and refetches session', async () => {
    vi.mocked(api.getSupportArtifacts).mockRejectedValue(new ApiError(403, { error: 'support_access_denied', reason: 'permission_missing', permission: 'ViewBackupMetadata' }))
    mount('?tab=browser')
    expect(await screen.findByRole('alert')).toHaveTextContent('Destek oturumunda bu işlem için gereken izin yok')
    expect(screen.getByRole('heading', { name: 'Bu alan için yetkiniz yok' })).toBeInTheDocument()
    await waitFor(() => expect(vi.mocked(api.getSession).mock.calls.length).toBeGreaterThanOrEqual(2))
  })
  it('404 renders the support session not-found state without requesting customer data', async () => {
    vi.mocked(api.getSession).mockRejectedValue(new ApiError(404, { error: 'support_session_not_found' }))
    mount('?tab=restores')
    expect(await screen.findByRole('alert')).toHaveTextContent('Destek oturumu bulunamadı')
    for (const fn of dataFunctions()) expect(fn).not.toHaveBeenCalled()
  })
  it('a server-skew corrected elapsed countdown disables access even before the Active row refetch returns', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ serverNow: '2026-10-09T12:00:00Z', expiresAt: '2026-10-09T11:59:59Z' }))
    mount('?tab=browser')
    await screen.findByRole('heading', { name: /Acme A.Ş. · (?:Support Session|Destek Oturumu)/ })
    expect(screen.getByRole('button', { name: "Oturumu kapat" })).toBeDisabled()
    expect(screen.getByRole('tab', { name: "Yedekleme Gezgini" })).toBeDisabled()
    expect(screen.getByText(/Destek oturumunun süresi doldu/)).toBeInTheDocument()
    for (const fn of dataFunctions()) expect(fn).not.toHaveBeenCalled()
  })
  it('switching the route removes previous-session metadata and never displays it for a different tenant/session', async () => {
    vi.mocked(api.getSession).mockImplementation(async id => makeSession(id === 'support-a' ? {} : { id, tenantId: 'tenant-b', tenantName: 'Other Tenant' }))
    vi.mocked(api.getSupportArtifacts).mockImplementation(async id => id === 'support-a' ? paged([makeArtifact({ databaseName: 'Private Customer A' })]) : paged([makeArtifact({ id: 'artifact-b', databaseName: 'Other Customer B' })]))
    const { client } = renderPlatform(<><Link to="/platform/support-sessions/support-b?tab=browser">Diğer oturum</Link><PlatformSupportSessionPage /></>, { path: '/platform/support-sessions/support-a?tab=browser', route: '/platform/support-sessions/:sessionId' })
    await screen.findByRole('button', { name: 'Private Customer A' })
    fireEvent.click(screen.getByRole('link', { name: 'Diğer oturum' }))
    await screen.findByRole('heading', { name: /Other Tenant · (?:Support Session|Destek Oturumu)/ })
    expect(screen.queryByText('Private Customer A')).not.toBeInTheDocument()
    expect(client.getQueryCache().getAll().filter(query => query.queryKey[3] === 'support-a' && query.queryKey[4] === 'tenant')).toHaveLength(0)
    await screen.findByRole('button', { name: 'Other Customer B' })
    expect(client.getQueryCache().getAll().some(query => query.queryKey[3] === 'support-b' && query.queryKey[5] === 'tenant-b')).toBe(true)
    removeSupportData(client, 'support-b')
  })
  it('audit remains accessible for ended sessions while customer-data requests stay disabled', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ status: 'Closed' }))
    vi.mocked(api.getSessionAudit).mockResolvedValue(paged([{ id: 'audit-a', at: new Date().toISOString(), action: 'support.session_closed', actorUserId: 'admin-id', actorDisplayName: 'Platform Operatörü', targetType: 'SupportSession', targetId: 'support-a', result: 'succeeded', details: {} }]))
    mount('?tab=audit')
    await screen.findByText('support.session_closed')
    expect(api.getSessionAudit).toHaveBeenCalledWith('support-a', { page: 1, pageSize: 25 }, expect.any(AbortSignal))
    for (const fn of dataFunctions()) expect(fn).not.toHaveBeenCalled()
  })
  it('restore detail permits metadata viewing but cancellation still needs RestoreBackup', async () => {
    vi.mocked(api.getSession).mockResolvedValue(makeSession({ permissions: ['ViewBackupMetadata'] }))
    vi.mocked(api.getSupportRestore).mockResolvedValue(makeRestore({ id: 'execution-a', purpose: 'Execution', status: 'Running', targetState: 'Unknown' }))
    mount('?tab=restores&restoreId=execution-a')
    expect(await screen.findByRole('button', { name: "Geri yüklemeyi iptal et" })).toBeDisabled()
    expect(screen.getByText(/Ajan hedef veritabanının durumunu belirleyemedi|Ajan hedef Veritabanı durumunu belirleyemedi/)).toBeInTheDocument()
    expect(api.cancelSupportRestore).not.toHaveBeenCalled()
  })
  it('a denied cancel renders the authorization state and refreshes the session rather than trusting stale permissions', async () => {
    vi.mocked(api.getSupportRestore).mockResolvedValue(makeRestore({ id: 'execution-a', purpose: 'Execution', status: 'Running' }))
    vi.mocked(api.cancelSupportRestore).mockRejectedValue(new ApiError(403, { error: 'support_access_denied', reason: 'session_revoked' }))
    mount('?tab=restores&restoreId=execution-a')
    fireEvent.click(await screen.findByRole('button', { name: "Geri yüklemeyi iptal et" }))
    fireEvent.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'İptali onayla' }))
    expect(await screen.findByRole('heading', { name: 'Bu alan için yetkiniz yok' })).toBeInTheDocument()
    expect(screen.getAllByText('Destek erişimi geri alındı.').length).toBeGreaterThan(0)
    await waitFor(() => expect(vi.mocked(api.getSession).mock.calls.length).toBeGreaterThanOrEqual(2))
  })
})
