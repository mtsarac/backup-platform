#!/usr/bin/env python3
"""Idempotent local-development bootstrap, driven only through the real backend HTTP API (no database writes, no auth bypass).

  init-accounts  writes docs/local-development-accounts.txt (0600) with generated passwords; never overwrites an existing file.
  get            prints one value of that file (used only to hand the first PlatformAdmin password to the real bootstrap CLI).
  enrollment-token  Tenant Owner creates a one-time Agent enrollment token in a 0600 file.
  seed           PlatformAdmin logs in, then ensures: tenant, Owner + Operator users and memberships, a 5 GB (decimal) plan,
                 an Active subscription and agent enrollment. Re-running creates nothing twice.

Passwords exist only in the owner-only accounts file and are never printed.
"""
import argparse
import importlib.util
import os
from pathlib import Path
import secrets
import sys

spec = importlib.util.spec_from_file_location('quota_fixture', Path(__file__).parent.parent / 'frontend' / 'quota-smoke-fixture.py')
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)
Api, FixtureFailure = shared.Api, shared.FixtureFailure

TENANT_NAME = 'Local Development Tenant'
PLAN_NAME = 'Local Development 5 GB'
PLAN_BYTES = 5_000_000_000  # 1 GB = 1,000,000,000 bytes (product decision)
MSSQL_TEST_DATABASE = 'bp_google_drive_acceptance'


def read_accounts(path):
    values = {}
    for line in Path(path).read_text().splitlines():
        if line and not line.startswith('#') and ': ' in line:
            key, value = line.split(': ', 1)
            values[key.strip()] = value.strip()
    return values


def password():
    return 'Dev-' + secrets.token_hex(12) + '!'


def init_accounts(options):
    if os.path.exists(options.accounts_file):
        print('Accounts file already exists; left untouched.')
        return
    rows = [
        ('frontend_url', options.frontend), ('backend_url', options.backend), ('database', options.database + ' (PostgreSQL, container postgres)'),
        ('tenant_name', TENANT_NAME),
        ('platform_admin_login', 'dev.platformadmin'), ('platform_admin_password', password()),
        ('tenant_owner_login', 'dev.owner'), ('tenant_owner_password', password()),
        ('tenant_operator_login', 'dev.operator'), ('tenant_operator_password', password()),
        ('mssql_test_database', MSSQL_TEST_DATABASE + ' (container bp-dev-mssql, 127.0.0.1:' + str(options.mssql_port) + ', login sa)'),
        ('backup_job_sql_credential_reference', options.sql_reference),
    ]
    text = '# Local development accounts. Private: never commit or share. Generated by scripts/dev/bootstrap.py.\n' + ''.join(f'{k}: {v}\n' for k, v in rows)
    shared.write_private(options.accounts_file + '.tmp', {})  # creates the 0600 file before any secret is written
    fd = os.open(options.accounts_file + '.tmp', os.O_WRONLY | os.O_TRUNC | os.O_NOFOLLOW)
    with os.fdopen(fd, 'w') as handle:
        handle.write(text)
    os.replace(options.accounts_file + '.tmp', options.accounts_file)
    print('Accounts file created (0600).')


def find_by(items, key, value):
    return next((item for item in items if item[key] == value), None)


def ensure_user(platform, accounts, prefix, display):
    login = accounts[prefix + '_login']
    status, user = platform.call('POST', '/api/platform/users',
                                 {'loginIdentifier': login, 'password': accounts[prefix + '_password'], 'displayName': display}, expect=(201, 409))
    if status == 201:
        return user['userId']
    _, page = platform.call('GET', '/api/platform/users?search=' + login + '&pageSize=100')
    return find_by(page['items'], 'loginIdentifier', login)['userId']


def seed(options):
    accounts = read_accounts(options.accounts_file)
    platform = Api(options.server, options.certificate)
    platform.login(accounts['platform_admin_login'], accounts['platform_admin_password'])

    _, tenants = platform.call('GET', '/api/platform/tenants?search=' + TENANT_NAME.replace(' ', '%20') + '&pageSize=100')
    tenant = find_by(tenants['items'], 'name', TENANT_NAME)
    if tenant is None:
        _, tenant = platform.call('POST', '/api/platform/tenants', {'name': TENANT_NAME})
    tenant_id = tenant['tenantId']

    for prefix, display, role in (('tenant_owner', 'Local Owner', 'Owner'), ('tenant_operator', 'Local Operator', 'Operator')):
        user_id = ensure_user(platform, accounts, prefix, display)
        platform.call('POST', f'/api/platform/tenants/{tenant_id}/memberships', {'userId': user_id, 'role': role}, expect=(201, 409))

    _, plans = platform.call('GET', '/api/platform/plans?pageSize=100')
    plan = find_by(plans['items'], 'name', PLAN_NAME)
    if plan is None:
        _, plan = platform.call('POST', '/api/platform/plans', {'name': PLAN_NAME, 'storageLimitBytes': PLAN_BYTES, 'unlimited': False, 'enabled': True,
                                                               'quotaPolicyReference': options.quota_policy})
    _, current = platform.call('GET', f'/api/platform/tenants/{tenant_id}/subscription')
    subscription = current.get('subscription')
    if not subscription or subscription['planId'] != plan['planId'] or subscription['status'] != 'Active':
        platform.call('PUT', f'/api/platform/tenants/{tenant_id}/subscription', {'planId': plan['planId']})
    platform.call('PUT', f'/api/platform/tenants/{tenant_id}/subscription/storage-limit-override', {'kind': 'unlimited'})
    platform.call('PUT', f'/api/platform/tenants/{tenant_id}/agent-enrollment', {'enabled': True})
    print(f'Seed complete: tenant {tenant_id}, plan {plan["planId"]}')


def enrollment_token(options):
    accounts = read_accounts(options.accounts_file)
    platform = Api(options.server, options.certificate)
    platform.login(accounts['platform_admin_login'], accounts['platform_admin_password'])
    _, tenants = platform.call('GET', '/api/platform/tenants?search=' + TENANT_NAME.replace(' ', '%20') + '&pageSize=100')
    tenant_id = find_by(tenants['items'], 'name', TENANT_NAME)['tenantId']
    owner = Api(options.server, options.certificate)
    owner.login(accounts['tenant_owner_login'], accounts['tenant_owner_password'])
    _, token = owner.call('POST', f'/api/tenants/{tenant_id}/agent-enrollment-tokens', {})
    shared.write_private(options.output, {'token': token['token']})
    print('Enrollment token written (0600).')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    first = commands.add_parser('init-accounts')
    first.add_argument('--accounts-file', required=True)
    first.add_argument('--database', required=True)
    first.add_argument('--frontend', required=True)
    first.add_argument('--backend', required=True)
    first.add_argument('--mssql-port', type=int, required=True)
    first.add_argument('--sql-reference', required=True)
    second = commands.add_parser('get')
    second.add_argument('--accounts-file', required=True)
    second.add_argument('key')
    third = commands.add_parser('seed')
    third.add_argument('--accounts-file', required=True)
    third.add_argument('--server', required=True)
    third.add_argument('--certificate', required=True)
    third.add_argument('--quota-policy', default='default')
    fourth = commands.add_parser('enrollment-token')
    fourth.add_argument('--accounts-file', required=True)
    fourth.add_argument('--server', required=True)
    fourth.add_argument('--certificate', required=True)
    fourth.add_argument('--output', required=True)
    options = parser.parse_args()
    try:
        if options.command == 'get':
            print(read_accounts(options.accounts_file)[options.key])
        else:
            {'init-accounts': init_accounts, 'seed': seed, 'enrollment-token': enrollment_token}[options.command](options)
    except (FixtureFailure, OSError, ValueError, KeyError) as failure:
        print('FAIL: ' + (str(failure) if isinstance(failure, FixtureFailure) else 'bootstrap failed (details withheld): ' + type(failure).__name__), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
