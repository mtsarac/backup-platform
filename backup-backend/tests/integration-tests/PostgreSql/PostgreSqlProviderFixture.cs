    }

    public async Task<string> RoleAsync()
    {
        var role = $"bp_pgrole_{Guid.NewGuid():N}";
        _roles.Add(role);
        await ExecuteAsync(null, $"CREATE ROLE {Q(role)} NOLOGIN");
        return role;
    }
    public async Task<NpgsqlConnection> OpenAsync(string? database = null)
    {
        var builder = new NpgsqlConnectionStringBuilder(_admin) { Database = database ?? new NpgsqlConnectionStringBuilder(_admin).Database, Pooling = false };
        var connection = new NpgsqlConnection(builder.ConnectionString);
        await connection.OpenAsync();
        return connection;
    }
    public NpgsqlConnection HoldScratchAdvisoryLock(string target, long key)
    {
        using var admin = new NpgsqlConnection(_admin);
        admin.Open();
        using var find = new NpgsqlCommand("SELECT datname FROM pg_database WHERE datname LIKE 'bp_restore_%' AND shobj_description(oid,'pg_database') LIKE @target", admin);
        find.Parameters.AddWithValue("target", "%\"target\":\"" + target + "\"%");
        var database = (string?)find.ExecuteScalar() ?? throw new InvalidOperationException("The current attempt's scratch database must exist before the restore starts.");
        var held = new NpgsqlConnection(new NpgsqlConnectionStringBuilder(_admin) { Database = database, Pooling = false }.ConnectionString);
        try
        {
            held.Open();
            using var command = new NpgsqlCommand("SELECT pg_advisory_lock(@key)", held);
            command.Parameters.AddWithValue("key", key);
            command.ExecuteNonQuery();
            return held;
        }
        catch { held.Dispose(); throw; }
    }

    public async Task ExecuteAsync(string? database, string sql)
    {
        await using var connection = await OpenAsync(database);
        await using var command = new NpgsqlCommand(sql, connection) { CommandTimeout = 30 };
        await command.ExecuteNonQueryAsync();
    }
    public async Task<T?> ScalarAsync<T>(string? database, string sql)
    {
        await using var connection = await OpenAsync(database);
        await using var command = new NpgsqlCommand(sql, connection);
        var value = await command.ExecuteScalarAsync();
        return value is null or DBNull ? default : (T)Convert.ChangeType(value, typeof(T), CultureInfo.InvariantCulture);
    }
    public async Task<StagedBackupFile> DumpAsync(string database, string? file = null)
    {
        var result = await Backup.ExecuteFullBackupAsync(Settings, Credential,
            new FullBackupRequest(database, StagingArea.SameHost(DirectoryPath), file ?? $"{Guid.NewGuid():N}.dump",
                new FullBackupOptions(copyOnly: BackupOptionMode.Required, compression: BackupOptionMode.Required)), null, CancellationToken.None);
        Assert.True(result.Status == FullBackupStatus.Succeeded, result.Failure?.Message + " / " + result.Failure?.ReasonCode);
        Assert.Equal(BackupVerificationStatus.Passed, result.Verification.Status);
        Assert.True(result.Options!.Applied.CopyOnly);
        Assert.True(result.Options.Applied.Compression);
        Assert.Equal("PGDMP", System.Text.Encoding.ASCII.GetString((await File.ReadAllBytesAsync(result.StagedFile!.AgentPath.Value))[..5]));
        return result.StagedFile;
    }
    /// <summary>Prepare deliberately unsupported archives with the real tool, bypassing the provider's full-backup safety gate.</summary>
    public async Task<StagedBackupFile> NativeDumpAsync(string database)
    {
        var name = $"{Guid.NewGuid():N}.dump";
        var path = Path.Combine(DirectoryPath, name);
        var executable = OperatingSystem.IsWindows() ? "pg_dump.exe" : "pg_dump";
        var info = new System.Diagnostics.ProcessStartInfo(Options.ClientToolsDirectory is null ? executable : Path.Combine(Options.ClientToolsDirectory, executable))
        {
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true
        };
        foreach (var key in info.Environment.Keys.Where(key => key.StartsWith("PG", StringComparison.OrdinalIgnoreCase)).ToArray()) info.Environment.Remove(key);
        info.Environment["PGPASSWORD"] = Credential.Password.Reveal();
        info.Environment["LC_ALL"] = "C";
        info.Environment["PGCLIENTENCODING"] = "UTF8";
        foreach (var argument in new[] { "--no-password", "--host", Settings.Endpoint.Host, "--port", Settings.Endpoint.Port!.Value.ToString(CultureInfo.InvariantCulture),
                     "--username", Credential.UserName, "--dbname", database, "--format=custom", "--file", path })
            info.ArgumentList.Add(argument);
        using var process = new System.Diagnostics.Process { StartInfo = info };
        process.Start();
        var stdout = process.StandardOutput.BaseStream.CopyToAsync(Stream.Null);
        var stderr = process.StandardError.BaseStream.CopyToAsync(Stream.Null);
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(60));
        try { await process.WaitForExitAsync(timeout.Token); }
        finally
        {
            if (!process.HasExited) process.Kill(entireProcessTree: true);
            await process.WaitForExitAsync();
            await Task.WhenAll(stdout, stderr);
        }
        Assert.Equal(0, process.ExitCode);
        return new StagedBackupFile(new DatabaseServerPath(path), new AgentPath(path), name, new FileInfo(path).Length);
    }

    public async Task<RestoreBackupInspection> InspectAsync(StagedBackupFile file)
    {
        var result = await Restore.InspectBackupAsync(Settings, Credential,
            new RestoreInspectionRequest(file.ServerPath, true, agentFile: file.AgentPath), CancellationToken.None);
        Assert.Null(result.Failure);
        Assert.NotNull(result.Inspection);
        Assert.True(result.Inspection.VerifyOnlyPassed);
        Assert.Empty(result.Inspection.Files);
        return result.Inspection;
    }
    public async Task<DatabaseRestoreRequest> RequestAsync(string name, StagedBackupFile file, DatabaseRestoreMode mode = DatabaseRestoreMode.NewDatabase,
        bool terminate = false, RestoreBackupInspection? inspection = null)
    {
        inspection ??= await InspectAsync(file);
        var result = await Restore.PlanRestoreAsync(Settings, Credential, new RestorePlanRequest(name, mode, terminate, inspection), CancellationToken.None);
        Assert.True(result.Report.CanProceed, string.Join("; ", result.Report.Items.Where(x => x.Status == BackupPreCheckStatus.Failed).Select(x => x.ReasonCode + ": " + x.Message)));
        Assert.NotNull(result.Plan);
        Assert.Empty(result.Plan.Mappings);
        Assert.Null(result.Plan.Target.DefaultDataDirectory);
        return new DatabaseRestoreRequest(name, file.ServerPath, mode, terminate, inspection, result.Plan, agentFile: file.AgentPath);
    }

    public async Task<string> SnapshotAsync(string database)
    {
        var snapshots = new List<string>();
        string[] queries =
        [
            "SELECT row_to_json(t)::text FROM business.customer t ORDER BY id",
            "SELECT row_to_json(t)::text FROM business.orders t ORDER BY id",
            "SELECT row_to_json(t)::text FROM business.order_totals t ORDER BY customer_id",
            "SELECT indexdef FROM pg_indexes WHERE schemaname='business' ORDER BY indexname",
            "SELECT conname || ':' || pg_get_constraintdef(oid) FROM pg_constraint WHERE connamespace='business'::regnamespace ORDER BY conname",
            "SELECT sequencename || ':' || last_value::text FROM pg_sequences WHERE schemaname='business' ORDER BY sequencename",
            "SELECT encode(lo_get(payload),'hex') FROM business.blob_reference",
            "SELECT extname || ':' || extversion FROM pg_extension ORDER BY extname",
            "SELECT business.label('schema function')",
            "SELECT c.relname || ':' || pg_get_userbyid(c.relowner) || ':' || coalesce(c.relacl::text,'') FROM pg_class c WHERE c.relnamespace='business'::regnamespace ORDER BY c.relname",
            "SELECT obj_description('business.customer'::regclass, 'pg_class')"
        ];
        await using var connection = await OpenAsync(database);
        foreach (var query in queries)
        {
            await using var command = new NpgsqlCommand(query, connection);
            await using var reader = await command.ExecuteReaderAsync();
            while (await reader.ReadAsync()) snapshots.Add(reader.GetString(0));
            snapshots.Add("--end--");
        }
        return JsonSerializer.Serialize(snapshots);
    }

    public async Task<string[]> RecoveryDatabasesAsync(string target)
    {
        var names = new List<string>();
        await using var connection = await OpenAsync();
        await using var command = new NpgsqlCommand("SELECT datname FROM pg_database WHERE shobj_description(oid, 'pg_database') LIKE @pattern ORDER BY datname", connection);
        command.Parameters.AddWithValue("pattern", "%\"target\":\"" + target + "\"%");
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync()) names.Add(reader.GetString(0));
        return [.. names];
    }
    public async Task DisposeAsync()
    {
        foreach (var target in _databases.ToArray())
            foreach (var recovery in await RecoveryDatabasesAsync(target)) _databases.Add(recovery);
        foreach (var database in _databases)
            await ExecuteAsync(null, $"DROP DATABASE IF EXISTS {Q(database)} WITH (FORCE)");
        foreach (var role in _roles) await ExecuteAsync(null, $"DROP ROLE IF EXISTS {Q(role)}");
        if (Directory.Exists(DirectoryPath)) Directory.Delete(DirectoryPath, true);
    }
    public static string Q(string value) => "\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
}
