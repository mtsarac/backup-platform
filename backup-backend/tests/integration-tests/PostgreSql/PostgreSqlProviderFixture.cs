namespace BackupPlatform.IntegrationTests.PostgreSql;

/// <summary>No platform migrations or shared template: every database and role belongs to this fixture alone.</summary>
public sealed class PostgreSqlProviderFixture : IAsyncLifetime
{
    private readonly HashSet<string> _databases = new(StringComparer.Ordinal);
    private readonly HashSet<string> _roles = new(StringComparer.Ordinal);
    private string _admin = null!;
    public string DirectoryPath { get; } = Path.Combine(Path.GetTempPath(), $"bp_pg_provider_{Guid.NewGuid():N}");
    public PostgreSqlBackupProvider Backup { get; private set; } = null!;
    public PostgreSqlRestoreProvider Restore { get; private set; } = null!;
    public DatabaseConnectionSettings Settings { get; private set; } = null!;
    public PasswordDatabaseCredential Credential { get; private set; } = null!;
    public PostgreSqlProviderOptions Options { get; private set; } = null!;

    public async Task InitializeAsync()
    {
        var configured = Environment.GetEnvironmentVariable("BACKUP_PLATFORM_TEST_CONNECTION_STRING");
        if (string.IsNullOrWhiteSpace(configured)) throw new InvalidOperationException("Set BACKUP_PLATFORM_TEST_CONNECTION_STRING to an isolated PostgreSQL superuser test instance.");
        var builder = new NpgsqlConnectionStringBuilder(configured) { Pooling = false };
        if (string.IsNullOrEmpty(builder.Password)) throw new InvalidOperationException("Provider tests require password authentication, not peer/trust-only credentials.");
        _admin = builder.ConnectionString;
        Settings = new DatabaseConnectionSettings(new DatabaseEndpoint(builder.Host!, builder.Port), new DatabaseConnectionOptions(requireEncryption: false));
        Credential = new PasswordDatabaseCredential(builder.Username!, new DatabaseSecret(builder.Password));
        Options = new PostgreSqlProviderOptions(Environment.GetEnvironmentVariable("BACKUP_PLATFORM_TEST_POSTGRES_TOOLS_DIRECTORY"));
        Backup = new PostgreSqlBackupProvider(NullLogger<PostgreSqlBackupProvider>.Instance, Options);
        Restore = new PostgreSqlRestoreProvider(NullLogger<PostgreSqlRestoreProvider>.Instance, Options);
        Directory.CreateDirectory(DirectoryPath);
        await using var connection = await OpenAsync();
        await using var command = new NpgsqlCommand("SELECT rolsuper FROM pg_roles WHERE rolname = current_user", connection);
        if (await command.ExecuteScalarAsync() is not true) throw new InvalidOperationException("Provider tests require an isolated superuser connection.");
    }

    public string Name(string? requested = null) { var name = requested ?? $"bp_pgtest_{Guid.NewGuid():N}"; _databases.Add(name); return name; }
