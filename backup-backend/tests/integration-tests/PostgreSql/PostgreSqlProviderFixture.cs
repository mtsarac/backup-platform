            CREATE SCHEMA business;
            CREATE TYPE business.order_state AS ENUM ('pending', 'complete');
            CREATE TABLE business.customer(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
