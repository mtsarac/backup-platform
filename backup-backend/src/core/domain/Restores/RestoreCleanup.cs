using System.Text.RegularExpressions;

namespace BackupPlatform.Domain.Restores;

/// <summary>
/// Names of the databases the platform creates itself. 128 random bits make a name its own proof of origin: the platform only ever drops a database whose name
/// matches, and a user-requested restore can never target a name with a reserved prefix. Mirrors the provider-side vocabulary on purpose: the domain does not
/// depend on provider code.
/// </summary>
public static partial class PlatformDatabaseNames
{
    public const string VerificationPrefix = "bp_verify_";
    public const string RollbackPrefix = "bp_old_";

    public static string NewVerificationName() => VerificationPrefix + Guid.NewGuid().ToString("N");

    public static bool IsVerification(string? name) => name is not null && VerificationPattern().IsMatch(name);

    public static bool IsRollback(string? name) => name is not null && RollbackPattern().IsMatch(name);

    public static bool IsReserved(string? name) => name is not null &&
        (name.StartsWith(VerificationPrefix, StringComparison.OrdinalIgnoreCase) || name.StartsWith(RollbackPrefix, StringComparison.OrdinalIgnoreCase));

    [GeneratedRegex("^bp_verify_[0-9a-f]{32}$", RegexOptions.CultureInvariant)]
    private static partial Regex VerificationPattern();

    [GeneratedRegex("^bp_old_[0-9a-f]{32}$", RegexOptions.CultureInvariant)]
    private static partial Regex RollbackPattern();
}

/// <summary>Which platform-created database an operation is responsible for removing.</summary>
public enum RestoreCleanupKind
{
    None = 1,
    /// <summary>The disposable <c>bp_verify_*</c> database of a verification; the operation's own <see cref="RestoreOperation.DatabaseName"/>.</summary>
    VerificationDatabase = 2,
    /// <summary>The <c>bp_old_*</c> copy PostgreSQL kept when a restore replaced a database. Removed only when an operator asks.</summary>
    RollbackCopy = 3
}

public enum RestoreCleanupState
{
    /// <summary>Nothing to remove (yet): an ordinary operation, or a verification that has not ended.</summary>
    Idle = 1,
    /// <summary>A rollback copy exists and is kept until an operator decides; nothing removes it on its own.</summary>
    Retained = 2,
    /// <summary>The database may still exist and its removal is owed.</summary>
    Pending = 3,
    /// <summary>The database is confirmed gone.</summary>
    Completed = 4
}

/// <summary>
/// The durable record of a platform-created database an operation owes the target server's cleanup for. It survives agent crashes, backend restarts and
/// cancellations because the name is generated by the backend before anything exists, so a lost agent never leaves an unknown leftover. Removal is leased
/// and fenced with its own token (a stale report from an earlier lease is a conflict), retried with a bounded backoff, and parked for an operator after
/// <see cref="MaxAutomaticAttempts"/> failures instead of retrying forever. Immutable: every transition returns the next value.
/// </summary>
public sealed record RestoreCleanup
{
    public const int MaxAutomaticAttempts = 8;
    public static readonly TimeSpan MaxBackoff = TimeSpan.FromHours(1);

    public static RestoreCleanup None { get; } = new();

    public RestoreCleanupKind Kind { get; init; } = RestoreCleanupKind.None;
    public string? DatabaseName { get; init; }
    public RestoreCleanupState State { get; init; } = RestoreCleanupState.Idle;
    public int Attempts { get; init; }
    /// <summary>When the next automatic attempt may be leased; null while parked (Pending but waiting for an operator) or not pending.</summary>
    public DateTimeOffset? NextAttemptAt { get; init; }
    public Guid? LeaseToken { get; init; }
    public DateTimeOffset? LeaseExpiresAt { get; init; }
    /// <summary>The stable code of the last failed attempt.</summary>
    public string? LastFailureCode { get; init; }
    public DateTimeOffset? UpdatedAt { get; init; }
    public Guid? RequestedByUserId { get; init; }

    public bool IsPending => State == RestoreCleanupState.Pending;

    /// <summary>Pending with nothing scheduled: the automatic attempts are used up (or the last lease expired after the last one), so only an operator's retry continues.</summary>
    public bool NeedsAttention(DateTimeOffset now) => IsPending && (LeaseToken is null ? NextAttemptAt is null : LeaseExpiresAt <= now && Attempts >= MaxAutomaticAttempts);

    internal static RestoreCleanup ForVerification(string databaseName)
    {
        if (!PlatformDatabaseNames.IsVerification(databaseName)) throw new ArgumentException("A verification owns only a platform verification database.");
        return new RestoreCleanup { Kind = RestoreCleanupKind.VerificationDatabase, DatabaseName = databaseName };
    }

    internal static RestoreCleanup Retain(string databaseName, DateTimeOffset now)
    {
        if (!PlatformDatabaseNames.IsRollback(databaseName)) throw new ArgumentException("Only a platform rollback database can be retained.");
        return new RestoreCleanup { Kind = RestoreCleanupKind.RollbackCopy, DatabaseName = databaseName, State = RestoreCleanupState.Retained, UpdatedAt = now };
    }

    /// <summary>A verification ended: either the agent proved the database is gone (or never existed), or its removal is owed and starts now.</summary>
    internal RestoreCleanup Ended(bool removed, DateTimeOffset now) => Kind != RestoreCleanupKind.VerificationDatabase || State != RestoreCleanupState.Idle
        ? this
        : removed
            ? this with { State = RestoreCleanupState.Completed, UpdatedAt = now }
            : this with { State = RestoreCleanupState.Pending, NextAttemptAt = now, UpdatedAt = now };

    /// <summary>An operator asked for removal (a rollback copy) or for a retry now (a parked or backing-off removal). Resets the automatic budget. False when there is nothing to request.</summary>
    internal bool TryRequest(DateTimeOffset now, Guid? userId, out RestoreCleanup next)
    {
        next = this;
        if (!CanBeRequested(now)) return false;
        next = this with
        {
            State = RestoreCleanupState.Pending, Attempts = 0, NextAttemptAt = now, LeaseToken = null, LeaseExpiresAt = null, UpdatedAt = now, RequestedByUserId = userId
        };
        return true;
    }

    /// <summary>A removal owed or retained, with no attempt in flight (a live lease is somebody's attempt; another request is not stacked on it).</summary>
    public bool CanBeRequested(DateTimeOffset now) => State is RestoreCleanupState.Retained or RestoreCleanupState.Pending && !(LeaseToken is not null && LeaseExpiresAt > now);

    /// <summary>Due: backing off is over, or the previous lease expired unanswered (an agent that died mid-removal) and the automatic budget is not used up.</summary>
    public bool CanLease(DateTimeOffset now) => IsPending && (LeaseToken is null ? NextAttemptAt <= now : LeaseExpiresAt <= now && Attempts < MaxAutomaticAttempts);

    internal RestoreCleanup Leased(Guid token, DateTimeOffset now, TimeSpan duration)
    {
        if (!CanLease(now)) throw new InvalidOperationException("The cleanup cannot be leased.");
        if (token == Guid.Empty || duration <= TimeSpan.Zero) throw new ArgumentException("Invalid cleanup lease.");
        return this with { Attempts = Attempts + 1, LeaseToken = token, LeaseExpiresAt = now + duration, NextAttemptAt = null, UpdatedAt = now };
    }

    /// <summary>
    /// The agent's report for the lease it holds. A late success is accepted even after the lease expired (the database is gone either way) as long as nobody
    /// leased it since; a different token is a stale worker and is refused. The same report repeated is accepted unchanged.
    /// </summary>
    internal RestoreCleanup Reported(Guid token, bool removed, string? failureCode, DateTimeOffset now)
    {
        // Completed is final: a repeated or late report changes nothing.
        if (State == RestoreCleanupState.Completed) return this;
        if (!IsPending || token == Guid.Empty || LeaseToken != token) throw new InvalidOperationException("The cleanup lease is not current.");
        if (removed) return this with { State = RestoreCleanupState.Completed, LeaseToken = null, LeaseExpiresAt = null, NextAttemptAt = null, LastFailureCode = null, UpdatedAt = now };
        var next = Attempts >= MaxAutomaticAttempts ? (DateTimeOffset?)null : now + Backoff(Attempts);
        return this with { LeaseToken = null, LeaseExpiresAt = null, NextAttemptAt = next, LastFailureCode = failureCode, UpdatedAt = now };
    }

    public static TimeSpan Backoff(int attempts) => TimeSpan.FromMinutes(Math.Min(MaxBackoff.TotalMinutes, Math.Pow(2, Math.Clamp(attempts - 1, 0, 10))));
}
